"""The `serp test` subcommand: discover test_*.py files, build them natively,
run them, and report PASS/FAIL (a test passes when it exits 0).

Discovery: an explicit file or directory argument, else `tests/` next to
serp.toml (walking up from the current directory), else `tests/` in the
current directory. Pairs with the serp-test assertion library, but any
Serpentine program works as a test.
"""

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

from .project import find_manifest


def _discover(arg: str | None) -> list[Path]:
    """Resolve the test target to a sorted list of test files."""
    if arg:
        p = Path(arg).resolve()
        if p.is_file():
            return [p]
        if p.is_dir():
            return sorted(p.rglob("test_*.py"))
        return []
    mpath = find_manifest(Path.cwd())
    base = mpath.parent if mpath else Path.cwd()
    tdir = base / "tests"
    if tdir.is_dir():
        return sorted(tdir.rglob("test_*.py"))
    return []


def _testcase_classes(tc, module_name: str) -> list:
    """Find TestCase subclasses defined in the entry module, with their test methods."""
    base = ("serp_test", "TestCase")
    out = []
    for key in sorted(tc.classes):
        if key[0] != module_name or not tc.inherits_from(key, base):
            continue
        info = tc.classes[key]
        methods = sorted(n for n, sig in info.methods.items()
                         if n.startswith("test") and len(sig.params) == 1)
        if methods:
            out.append((key[1], methods, info))
    return out


def _gen_driver(module_name: str, cases: list) -> str:
    """Generate the runner module source for the discovered TestCase subclasses."""
    lines = ['"""Generated by `serp test` — runs the module\'s TestCase subclasses."""',
             "import sys",
             f"from {module_name} import " + ", ".join(sorted(c[0] for c in cases)),
             ""]
    runners = []
    for cls, methods, _info in cases:
        for m in methods:
            fn = f"_serp_run_{cls}_{m}"
            runners.append(fn)
            lines += [
                f"def {fn}() -> int:",
                f'    """Run {cls}.{m} with setUp/tearDown."""',
                f"    t: {cls} = {cls}()",
                "    t.setUp()",
                "    bad: int = 0",
                "    try:",
                f"        t.{m}()",
                "    except AssertionError as e:",
                f'        print(f"FAIL: {m} ({cls}) - {{e}}")',
                "        bad = 1",
                "    except Exception as e:",
                f'        print(f"ERROR: {m} ({cls}) - {{e}}")',
                "        bad = 1",
                "    t.tearDown()",
                "    return bad",
                "",
            ]
    lines += ["def main() -> None:",
              '    """Run every discovered test method and report a unittest-style summary."""',
              "    failures: int = 0"]
    lines += [f"    failures += {fn}()" for fn in runners]
    lines += [f'    print(f"Ran {len(runners)} test(s)")',
              "    if failures > 0:",
              '        print(f"FAILED (failures={failures})")',
              "        sys.exit(1)",
              '    print("OK")',
              "",
              'if __name__ == "__main__":',
              "    main()",
              ""]
    return "\n".join(lines)


def cmd_test(args: argparse.Namespace) -> int:
    """serp test: build (debug, default backend) and run every discovered test."""
    from .diagnostics import Reporter, SerpError
    from .cli import run_check
    tests = _discover(args.path)
    if not tests:
        where = args.path or "tests/"
        print(f"serp: no test_*.py files found under {where}", file=sys.stderr)
        return 1
    from .llvmbuild import LLVMBuildError, llvmlite_missing
    missing = llvmlite_missing()
    if missing:
        print(missing, file=sys.stderr)
        return 2
    from .llvmgen import LLVMUnsupported, build_llvm_native
    out_dir = Path(tempfile.mkdtemp(prefix="serp_test_"))
    failed = []
    for test in tests:
        label = str(test.relative_to(Path.cwd())) if test.is_relative_to(Path.cwd()) else str(test)
        rep = Reporter()
        try:
            tc = run_check(test, rep)
        except SerpError:
            failed.append(label)
            print(f"FAIL {label} (check)")
            print(rep.render_all(), file=sys.stderr)
            continue
        run_target = test
        driver: Path | None = None
        cases = _testcase_classes(tc, test.stem)
        if cases:
            bad_ctor = [c for c, _m, info in cases
                        if len(info.field_defaults) != len(info.field_order)]
            if bad_ctor:
                failed.append(label)
                print(f"FAIL {label}: TestCase subclass '{bad_ctor[0]}' must default "
                      f"every field (tests are constructed with no arguments)")
                continue
            driver = test.parent / f"_serp_driver_{test.stem}.py"
            driver.write_text(_gen_driver(test.stem, cases), encoding="utf-8")
            rep2 = Reporter()
            try:
                tc = run_check(driver, rep2)
            except SerpError:
                failed.append(label)
                print(f"FAIL {label} (driver check)")
                print(rep2.render_all(), file=sys.stderr)
                driver.unlink()
                continue
            run_target = driver
        exe = out_dir / (run_target.stem + (".exe" if sys.platform == "win32" else ""))
        try:
            build_llvm_native(tc, exe, debug=not args.release, debuginfo=False)
        except (LLVMUnsupported, LLVMBuildError) as exc:
            failed.append(label)
            print(f"FAIL {label} (build): {exc}")
            if driver is not None:
                driver.unlink()
            continue
        proc = subprocess.run([str(exe)], cwd=str(test.parent), capture_output=True)
        if driver is not None:
            driver.unlink()
        if proc.returncode != 0:
            failed.append(label)
            print(f"FAIL {label} (exit {proc.returncode})")
            tail = (proc.stderr or proc.stdout).decode("utf-8", errors="replace").strip()
            if tail:
                print("  " + "\n  ".join(tail.splitlines()[-10:]))
            continue
        if cases:
            out = proc.stdout.decode("utf-8", errors="replace").strip()
            if out:
                print("  " + "\n  ".join(out.splitlines()))
        print(f"PASS {label}")
    n = len(tests)
    print(f"\nserp: {n - len(failed)}/{n} test file(s) passed")
    return 1 if failed else 0


def register(sub) -> None:
    """Attach the test subcommand to the serp argument parser."""
    p_test = sub.add_parser("test", help="discover, build, and run test_*.py files")
    p_test.add_argument("path", nargs="?", default=None,
                        help="test file or directory (default: tests/ next to serp.toml)")
    p_test.add_argument("--release", action="store_true", help="optimized builds")
    p_test.set_defaults(func=cmd_test)

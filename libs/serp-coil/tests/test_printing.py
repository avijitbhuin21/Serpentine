"""Printing parity: repr/str of Coil arrays must match numpy's array2string byte for byte."""
from serp_coil import (arange, array, eye, inf, linspace, nan, ndarray, reshape, zeros)
from serpentine import Ref


def show(a: Ref[ndarray]) -> None:
    print(f"{a!r}")
    print(a)
    print("---")


def main() -> None:
    show(array([1.0, 2.0, 3.0]))
    show(array([1.5, 2.0, 3.0]))
    show(array([-1.5, 2.0, 30.25]))
    show(array([1, 2, 3]))
    show(array([-1, 20, 3]))
    show(array([True, False]))
    show(array([[1.0, 2.0], [3.0, 4.0]]))
    show(array([[1, 2], [3, 40]]))
    show(array([0.1, 0.25, 1.0 / 3.0]))
    show(array([1e10, 1.0]))
    show(array([1e-5, 1.0]))
    show(array([123456789.0, 1.0]))
    show(array([1e16, 1.0]))
    show(array([], dtype="float64"))
    show(zeros((2, 3)))
    show(arange(20))
    show(arange(30) * 1.5)
    show(linspace(0, 1, 5))
    show(array([nan, 1.0, inf, -inf]))
    show(array([0.0, -0.0]))
    show(array([12345.678, 0.001]))
    show(array([1.0]))
    show(array([[1.0], [2.5]]))
    show(eye(3))
    show(array([1.123456789, 2.0]))
    show(array([100.0, 0.5]))
    show(array([1e5, 1.0]))
    show(array([99999999.0, 1.0]))
    show(array([100000000.0, 1.0]))
    show(array([0.0001, 1.0]))
    show(array([0.00001, 1.0]))
    show(arange(1001))
    show(reshape(arange(24), (4, 6)).astype("float64"))
    show(array([1e-10, 2e-10]))
    show(array([1.5e300, 2.0]))
    show(array([3.0, 4.0]) / 7.0)
    show(arange(10) / 7.0)
    show(array([nan, nan]))
    show(array([1e10, nan]))
    show(array([-1e-7, 5.0]))
    show(array([True, True]))
    show(array([[True, False], [False, True]]))
    show(zeros((3, 40)))
    show(reshape(arange(60), (3, 20)))
    show(arange(2000) * 0.5)
    show(reshape(arange(1200), (30, 40)))
    show(array([-0.5, 0.5]))
    show(array([123.456, -0.001]))
    show(array([1.0, 2.0]) ** 60)
    show(array([2, 3]) ** 10)


if __name__ == "__main__":
    main()
